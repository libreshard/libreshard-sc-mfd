// Builds icons.css from tools/icons.js: one .i-<name> class per icon, as an SVG mask embedded as a
// data: URL. Embedded, because mask-image is fetched with CORS and the shard's iframe has an opaque
// origin, so a mask file from the shard's own folder wouldn't load.
// Usage: node tools/build-icons.js [--check]   (--check only reports a stale icons.css, exit 1)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const icons = require('./icons');

function css() {
  const rules = Object.entries(icons).map(([name, body]) => {
    const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" ' +
      'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + body + '</svg>';
    // Only the characters a data: URL can't hold are escaped; double quotes become single ones
    const data = svg.replace(/"/g, "'").replace(/[<>#%{}]/g, encodeURIComponent);
    return `.i-${name} { --icon: url("data:image/svg+xml,${data}"); }`;
  });
  return '/* Generated by tools/build-icons.js from tools/icons.js: do not edit here. */\n' + rules.join('\n') + '\n';
}

const file = path.join(root, 'icons.css');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== css()) { console.error('icons.css is stale: run node tools/build-icons.js'); process.exit(1); }
  console.log('icons.css is up to date.');
} else {
  fs.writeFileSync(file, css());
  console.log(`icons.css: ${Object.keys(icons).length} icons`);
}
